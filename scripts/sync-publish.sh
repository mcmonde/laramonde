#!/usr/bin/env bash
# Rewrite publish.yml from POSTGRES_PUBLISH, REDIS_PUBLISH, and
# MEILI_PUBLISH. An empty value adds no host port. Compose's ${VAR:-default}
# treats empty as unset, which is why Postgres used to publish anyway.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=scripts/_lib.sh
source "$ROOT/scripts/_lib.sh"

OUT="$ROOT/publish.yml"

# Host spec only. The container port is appended by this script.
is_publish_spec() {
  local v="$1"
  [[ "$v" =~ ^[0-9]{1,5}$ ]] && return 0
  [[ "$v" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}:[0-9]{1,5}$ ]] && return 0
  [[ "$v" =~ ^\[[0-9A-Fa-f:]+\]:[0-9]{1,5}$ ]] && return 0
  [[ "$v" =~ ^[A-Za-z0-9.-]+:[0-9]{1,5}$ ]] && return 0
  return 1
}

read_spec() {
  local key="$1"
  local value=""
  if [[ -f "$ROOT/.env" ]]; then
    value="$(env_get "$key" "$ROOT/.env")"
  fi
  if [[ -z "$value" ]]; then
    printf ''
    return 0
  fi
  if ! is_publish_spec "$value"; then
    echo "${key} is set but is not a host:port (or port). Refusing to publish." >&2
    return 1
  fi
  printf '%s' "$value"
}

spec_pg="$(read_spec POSTGRES_PUBLISH)"
spec_redis="$(read_spec REDIS_PUBLISH)"
spec_meili="$(read_spec MEILI_PUBLISH)"

tmp="$(mktemp "${OUT}.tmp.XXXXXX")"
{
  echo "# Host ports generated by scripts/sync-publish.sh."
  echo "# Empty POSTGRES_PUBLISH / REDIS_PUBLISH / MEILI_PUBLISH add no ports."
  if [[ -z "$spec_pg" && -z "$spec_redis" && -z "$spec_meili" ]]; then
    echo "services: {}"
  else
    echo "services:"
    if [[ -n "$spec_pg" ]]; then
      echo "  postgres:"
      echo "    ports:"
      echo "      - \"${spec_pg}:5432\""
    fi
    if [[ -n "$spec_redis" ]]; then
      echo "  redis:"
      echo "    ports:"
      echo "      - \"${spec_redis}:6379\""
    fi
    if [[ -n "$spec_meili" ]]; then
      echo "  meilisearch:"
      echo "    ports:"
      echo "      - \"${spec_meili}:7700\""
    fi
  fi
} > "$tmp"
mv "$tmp" "$OUT"

if [[ -z "$spec_pg" ]]; then echo "Postgres: not published"; else echo "Postgres: published on ${spec_pg}"; fi
if [[ -z "$spec_redis" ]]; then echo "Redis: not published"; else echo "Redis: published on ${spec_redis}"; fi
if [[ -z "$spec_meili" ]]; then echo "Meilisearch: not published"; else echo "Meilisearch: published on ${spec_meili}"; fi
